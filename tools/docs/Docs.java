    private static String json(List<Entry> list, String minecraft) {
        StringBuilder b = new StringBuilder("{\"version\":1,\"minecraft\":").append(q(minecraft)).append(",\"entries\":[");
        for (int i = 0; i < list.size(); i++) {
            Entry e = list.get(i);
            if (i > 0) b.append(',');
            b.append("\n{");
            boolean first = true;
            for (var kv : e.f().entrySet()) {
                if (!first) b.append(',');
                first = false;
                b.append(q(kv.getKey())).append(':').append(q(kv.getValue()));
            }
            b.append(",\"args\":").append(rows(e.args())).append(",\"expert\":").append(rows(e.expert()));
            b.append(",\"uses\":").append(strings(e.uses())).append(",\"usedBy\":").append(strings(e.usedBy()));
            b.append(",\"fields\":").append(rows(e.fields()));
            if (!e.tree().isEmpty()) b.append(",\"tree\":").append(rows(e.tree()));
            b.append('}');
        }
        return b.append("\n]}").toString();
    }

    private static String rows(List<String[]> rows) {
        StringJoiner j = new StringJoiner(",", "[", "]");
        for (String[] r : rows) j.add(strings(Arrays.asList(r)));
        return j.toString();
    }

    private static String strings(Collection<String> s) {
        StringJoiner j = new StringJoiner(",", "[", "]");
        for (String x : s) j.add(q(x));
        return j.toString();
    }

    private static String q(String s) {
        StringBuilder b = new StringBuilder("\"");
        for (char c : s.toCharArray()) {
            switch (c) {
                case '"' -> b.append("\\\"");
                case '\\' -> b.append("\\\\");
                case '\n' -> b.append("\\n");
                case '<' -> b.append("\\u003c"); // the JSON goes inside a <script>: no "</script>" can end it early
                default -> { if (c < 0x20) b.append(String.format("\\u%04x", (int) c)); else b.append(c); }
            }
        }
        return b.append('"').toString();
    }

    private static String markdown(List<Entry> list, String minecraft) {
        StringBuilder b = new StringBuilder("# Lullaby library (Minecraft " + minecraft + ")\n\nGenerated by tools/docs/Docs.java; do not edit.\n");
        for (Entry e : list) {
            var f = e.f();
            b.append("\n## ").append(f.get("name"));
            if (f.containsKey("fresh")) b.append(" *(").append(f.get("freshAs")).append(", ").append(f.get("freshDate")).append(")*");
            b.append("\n\n`").append(f.getOrDefault("syntax", f.get("name"))).append("`\n");
            if (f.containsKey("lead")) b.append('\n').append(f.get("lead")).append('\n');
            if (f.containsKey("note")) b.append("\n> ⚠ ").append(f.get("note")).append('\n');
            if (f.containsKey("text")) b.append('\n').append(f.get("text")).append('\n'); // guide pages: nearly Markdown
            if (!e.args().isEmpty()) {
                b.append("\n| argument | type | |\n|---|---|---|\n");
                for (String[] a : e.args()) b.append("| `").append(a[0]).append("` | ").append(a[1]).append(" | ").append(a[2]).append(" |\n");
            }
            if (!e.fields().isEmpty()) {
                b.append("\n| field | type | |\n|---|---|---|\n");
                for (String[] a : e.fields()) b.append("| `").append("event".equals(f.get("kind")) ? "e." : ".").append(a[0]).append("` | ").append(a[1]).append(" | ").append(a[2]).append(" |\n");
            }
            if (!e.tree().isEmpty()) {
                b.append('\n');
                for (String[] t : e.tree()) {
                    String[] path = t[0].split("\\.");
                    String name = path.length == 1 ? "e.packet == \"" + path[0] + "\"" : path.length == 2 ? "e." + path[1]
                            : "e." + path[1] + " == \"" + path[2] + "\"";
                    b.append("  ".repeat(path.length - 1)).append("- `").append(name).append('`')
                            .append(t[1].isEmpty() ? "" : " (" + t[1] + ")").append(": ").append(t[2]).append('\n');
                }
            }
            if (f.containsKey("returns")) b.append("\nReturns: ").append(f.get("returns")).append('\n');
            if (!e.uses().isEmpty()) b.append("\nUses: ").append(String.join(", ", e.uses())).append('\n');
            if (!e.usedBy().isEmpty()) b.append("\nUsed by: ").append(String.join(", ", e.usedBy())).append('\n');
            b.append("\nSource: ").append(f.get("src")).append('\n');
        }
        return b.toString();
    }

    /**
     * Definitions for the Lua language server (VS Code autocomplete). Types: "list of X" -> X[], text -> string.
     * Every page with field: lines gives a class of that name with those fields (is: gives its parent class); every
     * other page a type word names gets an empty class, so the type is known. A returns: line that is a plain type
     * list ("player · nil", "boolean (false if ...)": the words in brackets become the note) gives @return.
     */
    private static String luals(List<Entry> list) {
        StringBuilder b = new StringBuilder("---@meta\n-- Lullaby library definitions for the Lua language server. Generated, do not edit.\n");
        Map<String, Entry> byId = new HashMap<>();
        for (Entry e : list) byId.put(e.id(), e);
        // Classes first, each followed by a blank line, so none is bound to the function of the same name below.
        Set<String> classes = new TreeSet<>();
        for (Entry e : list) {
            if (e.f().containsKey("sub")) continue;
            if (!e.fields().isEmpty()) classes.add(e.id());
            List<String> words = new ArrayList<>();
            for (String[] a : e.args()) words.add(a[1]);
            for (String[] fl : e.fields()) words.add(fl[1]);
            if (returnTypes(e) != null) words.add(returnTypes(e)[0]);
            for (String w : words) for (String t : w.split("·")) {
                t = t.trim().replaceFirst("^list of ", "");
                // not Lua's own pages (function, table, ...): those are Lua's types already
                if (byId.containsKey(t) && List.of("reading", "type").contains(byId.get(t).f().get("kind"))) classes.add(t);
            }
        }
        for (String c : classes) {
            Entry e = byId.get(c);
            b.append('\n').append("---@class ").append(c);
            if (e.f().containsKey("is")) b.append(" : ").append(e.f().get("is"));
            b.append('\n');
            for (String[] fl : e.fields()) {
                b.append("---@field ").append(fl[0]).append(' ').append(luaType(fl[1]));
                if (fl.length > 2 && !fl[2].isEmpty()) b.append(' ').append(fl[2]);
                b.append('\n');
            }
        }
        Set<String> tables = new HashSet<>(); // "java" of java.class: declared once, before its first function
        for (Entry e : list) {
            String kind = e.f().get("kind");
            if (kind.equals("java") || kind.equals("type") || kind.equals("lua") || kind.equals("guide") || e.f().containsKey("sub")) continue;
            b.append('\n');
            int dot = e.id().indexOf('.');
            if (dot > 0 && tables.add(e.id().substring(0, dot))) b.append(e.id(), 0, dot).append(" = {}\n");
            if (e.f().containsKey("lead")) b.append("--- ").append(e.f().get("lead")).append('\n');
            boolean named = e.f().getOrDefault("syntax", "").contains(e.id() + "{");
            if (named && !e.args().isEmpty()) {
                b.append("---@class lullaby.").append(e.id()).append("_args\n");
                for (String[] a : e.args())
                    for (String n : a[0].replace("?", "").split("/"))
                        b.append("---@field ").append(n.trim().matches("\\d+") ? "[" + n.trim() + "]" : n.trim()).append("? ").append(luaType(a[1])).append(' ').append(a[2]).append('\n');
                b.append("---@param a lullaby.").append(e.id()).append("_args\n");
                appendReturn(b, e);
                b.append("function ").append(e.id()).append("(a) end\n");
            } else {
                for (String[] a : e.args()) b.append("---@param ").append(a[0].replace("?", "").split("/")[0].trim()).append(' ').append(luaType(a[1])).append('\n');
                StringJoiner params = new StringJoiner(", ");
                for (String[] a : e.args()) params.add(a[0].replace("?", "").split("/")[0].trim());
                appendReturn(b, e);
                b.append("function ").append(e.id()).append('(').append(params).append(") end\n");
            }
        }
        return b.toString();
    }

    /** The returns: line as { types, note } when it is a plain type list (see luals), else null. "nothing": null. */
    private static String[] returnTypes(Entry e) {
        String r = e.f().get("returns");
        if (r == null) return null;
        String note = "";
        Matcher m = Pattern.compile("^(.*?)\\s*\\((.*)\\)$").matcher(r);
        if (m.matches()) { r = m.group(1); note = m.group(2); }
        for (String t : r.split("·")) if (!t.trim().matches("(list of )?[a-z_0-9]+")) return null;
        if (r.trim().equals("nothing")) return null;
        return new String[]{r, note};
    }

    private static void appendReturn(StringBuilder b, Entry e) {
        String[] r = returnTypes(e);
        if (r == null) return;
        b.append("---@return ").append(luaType(r[0]));
        if (!r[1].isEmpty()) b.append(" # ").append(r[1]);
        b.append('\n');
    }

    private static String luaType(String types) {
        StringJoiner j = new StringJoiner("|");
        for (String t : types.split("·")) {
            t = t.trim();
            if (t.isEmpty()) continue;
            if (t.startsWith("list of ")) t = luaType(t.substring(8)) + "[]";
            else if (t.equals("text")) t = "string";
            j.add(t);
        }
        return j.length() == 0 ? "any" : j.toString();
    }
