import java.io.IOException;
import java.lang.reflect.Method;
import java.lang.reflect.Modifier;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.*;
import java.util.jar.JarFile;
import net.kyori.adventure.text.Component;
import org.bukkit.Location;
import org.bukkit.World;
import org.bukkit.block.Block;
import org.bukkit.entity.HumanEntity;
import org.bukkit.entity.Player;
import org.bukkit.event.Cancellable;
import org.bukkit.event.Event;
import org.bukkit.inventory.ItemStack;

/**
 * Writes src/main/resources/lullaby/events.txt: every Paper event scripts can listen to, with its fields. Not part of
 * the plugin: a single-file Java program, run by the Gradle task `events` (before every build) with Paper's API on the
 * class path: `java -cp <paper-api and its libraries> tools/events/EventList.java <out file> <paper-api jar>`.
 *
 * <p>This program owns the rules; EventBridge.java (plugin) and Docs.java (docs site) only read the file:
 * <ul>
 * <li>An event is every public, non-abstract, non-deprecated class in the Paper API jar that extends Bukkit's
 *     {@code Event} and has a handler list (Bukkit can only listen to those). Its name is the class's simple name.
 * <li>A field is every public, non-static, non-deprecated method without parameters that returns something, from the
 *     event class or its parents below {@code Event} (not from Java itself: Object, Iterable). Name: {@code getJoinMessage()} -> {@code join_message},
 *     {@code isCancelled()} -> {@code cancelled}, {@code joinMessage()} -> {@code join_message} (snake_case). If two
 *     methods give one name, get... wins over is... over the plain name.
 * <li>A field's setter: a non-deprecated method with one parameter named {@code set} + the name, or the plain name
 *     ({@code setCancelled(boolean)}, {@code joinMessage(Component)}); with several, the one taking the getter's type.
 * <li>Kinds: what Lullaby makes of a Java type (see KINDS in the file's header below). "?Type" means Lullaby can't
 *     read (or set) a Type yet; the plugin gives a clear error for those instead of nil.
 * </ul>
 * The output is sorted, so the same Paper version always gives the same file.
 */
public final class EventList {

    private static final Set<String> NOT_FIELDS = Set.of("getHandlers", "getEventName", "isAsynchronous", "callEvent",
            "toString", "hashCode", "getClass");

    public static void main(String[] argv) throws IOException {
        Path out = Path.of(argv[0]);
        List<String> lines = new ArrayList<>();
        List<String> deprecated = new ArrayList<>(), noHandlers = new ArrayList<>();
        Map<String, Class<?>> events = new TreeMap<>();
        ClassLoader loader = EventList.class.getClassLoader();
        String api = "";
        for (int i = 1; i < argv.length; i++) {
            api = Path.of(argv[i]).getFileName().toString().replaceAll("^paper-api-|\\.jar$", "");
            try (JarFile jar = new JarFile(argv[i])) {
                for (var entries = jar.entries(); entries.hasMoreElements(); ) {
                    String path = entries.nextElement().getName();
                    if (!path.endsWith("Event.class")) continue; // Bukkit and Paper name every event ...Event
                    Class<?> c;
                    try {
                        c = Class.forName(path.substring(0, path.length() - 6).replace('/', '.'), false, loader);
                    } catch (ClassNotFoundException | LinkageError e) {
                        continue;
                    }
                    int mod = c.getModifiers();
                    if (!Event.class.isAssignableFrom(c) || c == Event.class || !Modifier.isPublic(mod)
                            || Modifier.isAbstract(mod) || c.isInterface()) continue;
                    String name = c.getSimpleName();
                    if (c.isAnnotationPresent(Deprecated.class)) { deprecated.add(name); continue; }
                    if (!hasHandlers(c)) { noHandlers.add(name); continue; }
                    Class<?> twin = events.put(name, c);
                    // FORMAT: generator, two Paper events with one simple name
                    if (twin != null) throw new IllegalStateException("two events are named " + name + ": "
                            + twin.getName() + " and " + c.getName() + " (EventList.java needs a naming rule for this)");
                }
            }
        }

        lines.add("# Every Paper event scripts can listen to, with its fields. GENERATED by tools/events/EventList.java");
        lines.add("# (Gradle task `events`, part of every build) from Paper's API: don't edit by hand. Read by EventBridge.java");
        lines.add("# (plugin) and tools/docs/Docs.java (docs site).");
        lines.add("# Event line: name <TAB> Java class <TAB> docs sub group <TAB> flags (cancellable, async: Paper fires it off the");
        lines.add("#   main thread) or -");
        lines.add("# Field line: <TAB> name <TAB> getter <TAB> read kind <TAB> setter <TAB> setter's parameter class <TAB> write kind");
        lines.add("#   <TAB> enum: its class's simple name, \":\" and its words when 16 or fewer (Result:deny,default,allow);");
        lines.add("#   - where there is none");
        lines.add("# KINDS: player world block location item_stack component text enum key uuid boolean integer number;");
        lines.add("#   ?Type: Lullaby can't read (or set) a Type yet");
        lines.add("paper-api\t" + api);
        int fieldCount = 0, changeable = 0;
        for (var event : events.entrySet()) {
            Class<?> c = event.getValue();
            List<String> flags = new ArrayList<>();
            if (Cancellable.class.isAssignableFrom(c)) flags.add("cancellable");
            if (event.getKey().startsWith("Async")) flags.add("async");
            lines.add(event.getKey() + "\t" + c.getName() + "\t" + sub(c) + "\t" + (flags.isEmpty() ? "-" : String.join(",", flags)));
            boolean any = false;
            for (String field : fields(c)) {
                lines.add("\t" + field);
                fieldCount++;
                String[] parts = field.split("\t");
                if (!parts[5].equals("-") && !parts[5].startsWith("?")) any = true;
            }
            if (any) changeable++;
        }
        if (!deprecated.isEmpty()) lines.add("# left out, deprecated by Paper: " + String.join(" ", sorted(deprecated)));
        if (!noHandlers.isEmpty()) lines.add("# left out, no handler list (Bukkit can't listen): " + String.join(" ", sorted(noHandlers)));
        Files.createDirectories(out.toAbsolutePath().getParent());
        Files.writeString(out, String.join("\n", lines) + "\n", StandardCharsets.UTF_8);
        System.out.println("events: " + events.size() + " events (" + changeable + " with a field scripts can change), "
                + fieldCount + " fields, " + deprecated.size() + " deprecated left out -> " + out);
    }

    private static List<String> sorted(List<String> list) {
        List<String> copy = new ArrayList<>(list);
        Collections.sort(copy);
        return copy;
    }

    /** Bukkit can listen only to events with a static getHandlerList() in the class or a parent. */
    private static boolean hasHandlers(Class<?> c) {
        for (Class<?> at = c; at != null && at != Event.class; at = at.getSuperclass()) {
            try {
                Method m = at.getDeclaredMethod("getHandlerList");
                if (Modifier.isStatic(m.getModifiers())) return true;
            } catch (NoSuchMethodException ignored) {
            }
        }
        return false;
    }

    /** "org.bukkit.event.block.BlockBreakEvent" -> "Block": the package part right after "event". */
    private static String sub(Class<?> c) {
        String[] parts = c.getPackageName().split("\\.");
        for (int i = 0; i < parts.length - 1; i++) {
            if (parts[i].equals("event")) return Character.toUpperCase(parts[i + 1].charAt(0)) + parts[i + 1].substring(1);
        }
        return "Other";
    }

    /** The field lines of one event, sorted by name. */
    private static List<String> fields(Class<?> c) {
        // name -> [rank, method]: get... 0, is... 1, plain 2; the lowest rank wins
        Map<String, Method> getters = new TreeMap<>();
        Map<String, Integer> ranks = new HashMap<>();
        Method[] methods = c.getMethods();
        Arrays.sort(methods, Comparator.comparing(Method::toGenericString)); // getMethods() has no fixed order
        for (Method m : methods) {
            Class<?> from = m.getDeclaringClass();
            // methods from Java itself (Object, Iterable's iterator/spliterator) are no event fields
            if (from == Event.class || from.getName().startsWith("java.") || m.getParameterCount() != 0 || m.getReturnType() == void.class
                    || Modifier.isStatic(m.getModifiers()) || m.isBridge() || m.isSynthetic()
                    || m.isAnnotationPresent(Deprecated.class) || NOT_FIELDS.contains(m.getName())) continue;
            String n = m.getName();
            int rank;
            String camel;
            if (n.length() > 3 && n.startsWith("get") && Character.isUpperCase(n.charAt(3))) { rank = 0; camel = n.substring(3); }
            else if (n.length() > 2 && n.startsWith("is") && Character.isUpperCase(n.charAt(2))) { rank = 1; camel = n.substring(2); }
            else { rank = 2; camel = Character.toUpperCase(n.charAt(0)) + n.substring(1); }
            String name = snake(camel);
            Integer had = ranks.get(name);
            if (had != null && had <= rank) continue;
            ranks.put(name, rank);
            getters.put(name, m);
        }
        List<String> out = new ArrayList<>();
        for (var g : getters.entrySet()) {
            Method getter = g.getValue();
            String n = getter.getName();
            String camel = n.startsWith("get") && ranks.get(g.getKey()) == 0 ? n.substring(3)
                    : n.startsWith("is") && ranks.get(g.getKey()) == 1 ? n.substring(2)
                    : Character.toUpperCase(n.charAt(0)) + n.substring(1);
            Method setter = setter(c, camel, getter.getReturnType());
            Class<?> type = getter.getReturnType();
            String values = "-";
            if (type.isEnum()) {
                // the constants' names from the class itself: getEnumConstants() would start the class, and some of
                // Paper's enums need a running server for that
                StringJoiner j = new StringJoiner(",");
                int count = 0;
                for (var f : type.getDeclaredFields()) {
                    if (f.isEnumConstant()) { j.add(f.getName().toLowerCase(Locale.ROOT)); count++; }
                }
                values = type.getSimpleName() + ":" + (count <= 16 ? j.toString() : "");
            }
            out.add(g.getKey() + "\t" + n + "\t" + readKind(type) + "\t"
                    + (setter == null ? "-\t-\t-" : setter.getName() + "\t" + setter.getParameterTypes()[0].getName()
                    + "\t" + writeKind(setter.getParameterTypes()[0])) + "\t" + values);
        }
        return out;
    }

    private static Method setter(Class<?> c, String camel, Class<?> type) {
        String plain = Character.toLowerCase(camel.charAt(0)) + camel.substring(1);
        List<Method> found = new ArrayList<>();
        for (Method m : c.getMethods()) {
            if (m.getParameterCount() == 1 && !Modifier.isStatic(m.getModifiers()) && !m.isBridge()
                    && !m.isAnnotationPresent(Deprecated.class)
                    && (m.getName().equals("set" + camel) || m.getName().equals(plain))) found.add(m);
        }
        if (found.isEmpty()) return null;
        found.sort(Comparator.comparing(Method::toGenericString));
        for (Method m : found) if (m.getParameterTypes()[0] == type) return m;
        for (Method m : found) if (!writeKind(m.getParameterTypes()[0]).startsWith("?")) return m;
        return found.get(0);
    }

    // ---- kinds: what Lullaby makes of a Java type --------------------------------------------------------------

    private static String readKind(Class<?> t) {
        if (t == Player.class || t == HumanEntity.class) return "player"; // a HumanEntity is a player on Paper
        if (t == World.class) return "world";
        if (t == Block.class) return "block";
        if (t == Location.class) return "location";
        if (t == ItemStack.class) return "item_stack";
        String common = common(t);
        if (common != null) return common;
        if (t.isEnum()) return "enum";
        if (net.kyori.adventure.key.Key.class.isAssignableFrom(t) || net.kyori.adventure.key.Keyed.class.isAssignableFrom(t)
                || org.bukkit.Keyed.class.isAssignableFrom(t)) return "key";
        if (t == UUID.class) return "uuid";
        return "?" + t.getSimpleName();
    }

    private static String writeKind(Class<?> t) {
        if (t == Location.class) return "location";
        if (t == ItemStack.class) return "item_stack";
        String common = common(t);
        if (common != null) return common;
        if (t.isEnum()) return "enum";
        return "?" + t.getSimpleName();
    }

    private static String common(Class<?> t) {
        if (Component.class.isAssignableFrom(t)) return "component";
        if (t == String.class) return "text";
        if (t == boolean.class || t == Boolean.class) return "boolean";
        if (t == int.class || t == Integer.class || t == long.class || t == Long.class || t == short.class
                || t == Short.class || t == byte.class || t == Byte.class) return "integer";
        if (t == double.class || t == Double.class || t == float.class || t == Float.class) return "number";
        return null;
    }

    /** "JoinMessage" -> "join_message", "UUID" -> "uuid", "HTTPServer" -> "http_server". */
    static String snake(String camel) {
        StringBuilder b = new StringBuilder();
        for (int i = 0; i < camel.length(); i++) {
            char ch = camel.charAt(i);
            if (Character.isUpperCase(ch) && i > 0) {
                char before = camel.charAt(i - 1);
                boolean nextLower = i + 1 < camel.length() && Character.isLowerCase(camel.charAt(i + 1));
                if (Character.isLowerCase(before) || Character.isDigit(before) || (Character.isUpperCase(before) && nextLower)) b.append('_');
            }
            b.append(Character.toLowerCase(ch));
        }
        return b.toString();
    }
}
